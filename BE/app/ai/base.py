from typing import Protocol

from app.schemas import AnswerPlan, ImageAnalysis, ImageAnswer, UserIntent


class AIProvider(Protocol):
    async def analyze_query(self, query: str, history: list[dict]) -> UserIntent: ...
    async def generate_answer(self, query: str, items: list[dict], intent: UserIntent) -> AnswerPlan: ...
    async def analyze_image(self, content: bytes, mime: str) -> ImageAnalysis: ...
    async def generate_image_answer(self, extraction: ImageAnalysis) -> ImageAnswer: ...
